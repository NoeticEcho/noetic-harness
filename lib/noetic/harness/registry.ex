defmodule Noetic.Harness.Registry do
  @moduledoc """
  The competency registry: 270 roles, their capabilities, and what each one is
  allowed to hold.

  ## The registry is not a process list

  This is the point the upstream specification makes first and it is worth
  repeating where the code lives: **270 roles are not 270 running agents.** The
  registry is a library of competencies. A workflow assembles a temporary team
  of three to five of them for one task and then the team stops existing.
  Instantiating more than a handful for ordinary work is a routing failure, not
  thoroughness.

  ## Where the data comes from

  `.agents/registry/agents.json` is generated by
  `.agents/tools/build_registry.py` from the upstream registry plus the
  inspectable derivation rules in `role_rules.json`, `domains.json` and
  `capabilities.json`. It is committed, so the runtime never needs the generator
  and a reviewer can read the result.

  A file in `.agents/registry/overrides/<id>.json` is a hand-authored partial
  merged over the generated entry. That is the escape hatch for a role whose
  derived capabilities are wrong or whose contract needs detail the rules cannot
  express — and it is why the generator never touches `overrides/`.

  ## Loading

  Every read goes through `load/0`, which returns the whole registry. There is
  no cache and no GenServer: this is a few hundred kilobytes read by short-lived
  mix tasks, and a cache would only introduce the question of when it is stale.
  """

  alias Noetic.Harness.{Loader, Plane}

  @type agent :: map()
  @type t :: %{
          agents: [agent()],
          by_id: %{String.t() => agent()},
          domains: %{String.t() => map()},
          capabilities: %{String.t() => map()},
          archetypes: %{String.t() => map()},
          nucleus: [String.t()]
        }

  @doc """
  Load the registry, its domains, capabilities and archetypes, with overrides
  merged.

  Returns `{:error, message}` rather than raising, because the first caller is
  the validator and its job is to report every problem it can reach rather than
  to die on the first one.
  """
  @spec load() :: {:ok, t()} | {:error, String.t()}
  def load do
    with {:ok, registry} <- Loader.cached_load(path("agents.json")),
         {:ok, domains} <- Loader.cached_load(path("domains.json")),
         {:ok, capabilities} <- Loader.cached_load(path("capabilities.json")),
         {:ok, archetypes} <- Loader.cached_load(path("archetypes.json")),
         {:ok, rules} <- Loader.cached_load(path("role_rules.json")),
         {:ok, overrides} <- load_overrides() do
      generated = Map.fetch!(registry, "agents")

      agents =
        Enum.map(generated, &apply_override(&1, overrides)) ++ added(generated, overrides)

      {:ok,
       %{
         agents: agents,
         by_id: Map.new(agents, &{&1["id"], &1}),
         domains: index(domains, "domains", "id"),
         capabilities: index(capabilities, "capabilities", "id"),
         archetypes: index(archetypes, "archetypes", "id"),
         nucleus: get_in(rules, ["nucleus", "ids"]) || []
       }}
    end
  end

  @doc "Load or raise. For mix tasks, where a broken registry is not a condition to handle."
  @spec load!() :: t()
  def load! do
    case load() do
      {:ok, registry} -> registry
      {:error, message} -> raise ArgumentError, message
    end
  end

  @doc "One agent by id."
  @spec fetch(t(), String.t()) :: {:ok, agent()} | :error
  def fetch(registry, id), do: Map.fetch(registry.by_id, id)

  @doc """
  Every agent that supplies **all** of the given capabilities.

  All, not any: a step that needs `typedb.schema` and `semantic.modeling` needs
  one role that holds both, because splitting them across two roles means
  neither is accountable for the result.

  **Development roles only, unless `plane` says otherwise**. The
  conductor staffs a dispatched step through here, so a runtime role answered
  here would be a runtime role started by the development engine. `:any`
  takes both, for a listing.
  """
  @spec supplying(t(), [String.t()], Plane.t() | :any) :: [agent()]
  def supplying(registry, capabilities, plane \\ "development")

  def supplying(_registry, [], _plane), do: []

  def supplying(registry, capabilities, plane) do
    wanted = MapSet.new(capabilities)

    registry.agents
    |> Enum.filter(fn agent ->
      agent["status"] == "active" and Plane.in?(agent, plane) and
        MapSet.subset?(wanted, MapSet.new(agent["capabilities"]))
    end)
  end

  @doc """
  Every agent that supplies at least one of the capabilities, with the count.

  The fallback when nothing supplies all of them: better to report "the closest
  role covers two of your three capabilities" than to report nothing and let the
  caller assume the work is unroutable. Development roles only unless `plane`
  says otherwise, as `supplying/3`.
  """
  @spec partially_supplying(t(), [String.t()], Plane.t() | :any) ::
          [{agent(), non_neg_integer()}]
  def partially_supplying(registry, capabilities, plane \\ "development") do
    wanted = MapSet.new(capabilities)

    registry.agents
    |> Enum.filter(&(&1["status"] == "active" and Plane.in?(&1, plane)))
    |> Enum.map(fn agent ->
      {agent, MapSet.size(MapSet.intersection(wanted, MapSet.new(agent["capabilities"])))}
    end)
    |> Enum.reject(fn {_agent, count} -> count == 0 end)
    |> Enum.sort_by(fn {agent, count} -> {-count, length(agent["capabilities"])} end)
  end

  @doc "Agents in one domain."
  @spec in_domain(t(), String.t()) :: [agent()]
  def in_domain(registry, domain), do: Enum.filter(registry.agents, &(&1["domain"] == domain))

  @doc """
  The minimum runtime population — the roles client adapters are generated for.

  Development roles only, whatever a runtime role's `nucleus` says: a coding
  client's subagent is a development thing, and a runtime role's door is
  `harness export`.
  """
  @spec nucleus(t()) :: [agent()]
  def nucleus(registry),
    do: Enum.filter(registry.agents, &(&1["nucleus"] && not Plane.runtime?(&1)))

  @doc "The roles of one plane."
  @spec on_plane(t(), Plane.t()) :: [agent()]
  def on_plane(registry, plane), do: Enum.filter(registry.agents, &Plane.in?(&1, plane))

  @doc """
  The hand-authored operational overlay for a role, if one exists.

  `.agents/roles/<id>.md`. Its absence is normal and not a defect: the archetype
  and the capability detail already give a role a working method. An overlay is
  for a role whose method has specifics worth spelling out, which is why the
  nucleus has them and the long tail does not.
  """
  @spec overlay(String.t()) :: {:ok, String.t()} | :error
  def overlay(id) do
    path = Path.join([Noetic.Harness.agents_path("roles"), "#{id}.md"])

    case File.read(path) do
      # An empty file is not an overlay. It would otherwise satisfy everything
      # that asks whether a role has one — the validator's check, the prompt
      # test, the renderer — and leave the role with a `# Mission` heading and
      # no mission, which is worse than the honest fallback.
      {:ok, body} ->
        case String.trim(body) do
          "" -> :error
          trimmed -> {:ok, trimmed}
        end

      {:error, _} ->
        :error
    end
  end

  defp path(file), do: Path.join(Noetic.Harness.agents_path("registry"), file)

  defp load_overrides do
    dir = Path.join(Noetic.Harness.agents_path("registry"), "overrides")

    case Loader.load_dir(dir) do
      {:ok, entries} ->
        {:ok, Map.new(entries, fn {path, spec} -> {Path.basename(path, ".json"), spec} end)}

      error ->
        error
    end
  end

  # An override replaces the keys it names and leaves the rest. It cannot delete
  # a key, deliberately: a role whose override quietly removed `gates` would look
  # ungated rather than broken.
  @doc """
  What an override must carry to be read as a *new* role rather than a typo.

  The escape hatch could amend a generated role and nothing else:
  a file named for an id the generator has never heard of was loaded, matched
  nothing, and was silently dropped. The System One overlay proposes new roles,
  so the hatch has to be able to add one — and the moment it can, a mistyped
  filename becomes indistinguishable from a deliberate addition unless the
  addition is made to declare itself.

  Hence a required set rather than a flag. A file that carries all of these is
  a role; one that carries some of them is a broken override and
  `Noetic.Harness.Validation` says so by name instead of leaving a role quietly
  absent from a registry of 270.
  """
  @required_for_addition ~w(id name domain capabilities max_trust status)

  @spec required_for_addition() :: [String.t()]
  def required_for_addition, do: @required_for_addition

  @doc "Whether an override file describes a complete role."
  @spec addition?(map()) :: boolean()
  def addition?(spec) when is_map(spec),
    do: Enum.all?(@required_for_addition, &Map.has_key?(spec, &1))

  def addition?(_spec), do: false

  @doc """
  Override files that matched no generated role.

  Returns `{additions, orphans}` — the complete ones and the rest. The rest are
  what the validator reports; nothing else can see them, which is the point.
  """
  @spec unmatched([map()], %{String.t() => map()}) :: {[map()], [{String.t(), map()}]}
  def unmatched(generated, overrides) do
    known = MapSet.new(generated, & &1["id"])

    overrides
    |> Enum.reject(fn {id, _spec} -> MapSet.member?(known, id) end)
    |> Enum.split_with(fn {_id, spec} -> addition?(spec) end)
    |> then(fn {additions, orphans} ->
      {Enum.map(additions, fn {id, spec} ->
         spec |> Map.put("id", id) |> Map.put("added", true)
       end), orphans}
    end)
  end

  @doc "Load the override files, keyed by the id their filename names."
  @spec overrides() :: {:ok, %{String.t() => map()}} | {:error, String.t()}
  def overrides, do: load_overrides()

  defp added(generated, overrides) do
    {additions, _orphans} = unmatched(generated, overrides)
    additions
  end

  defp apply_override(agent, overrides) do
    case Map.fetch(overrides, agent["id"]) do
      {:ok, override} -> agent |> Map.merge(override) |> Map.put("overridden", true)
      :error -> agent
    end
  end

  defp index(doc, key, id_key) do
    doc |> Map.fetch!(key) |> Map.new(&{&1[id_key], &1})
  end
end
