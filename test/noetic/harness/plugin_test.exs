  # The publisher's name may be in the manifest's author, its links to the
  # public repository and the copyright line, and nowhere else.
  # The publisher's name where it may stand: the manifest's author and links,
  # links to the public repository anywhere, and the README's copyright line.
  defp scan_text(path) do
    text =
      if path == @manifest,
        do:
          manifest() |> Map.drop(~w(author homepage repository) ++ @page_fields) |> JSON.encode!(),
        else: path |> File.read!() |> String.replace(@copyright, "")

    String.replace(text, ~r{#{Regex.escape(@repository)}[^\s)>"]*}, "")
  end

  defp findings(text) do
    text = String.replace(text, @engine_names, "")

    words =
      for word <- @products ++ @stack,
          Regex.match?(Regex.compile!("(?<![a-z0-9_-])" <> word <> "(?![a-z0-9_])", "i"), text),
          do: String.replace(word, ["[", "]"], "")

    patterns =
      for {label, pattern} <- [
            {"a product name", ~r/n[o]etic/i},
            {"a home directory", ~r{/h[o]me/|/U[s]ers/}},
            {"a did:key", ~r/did:key:z[1-9A-HJ-NP-Za-km-z]{8,}/},
            {"an e-mail address", ~r/[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z]{2,}/},
            {"a bead id", ~r/\beb-[a-z0-9]{2,}/},
            {"an ADR number", ~r/\bADR-\d{3}\b/},
            {"Cyrillic text", ~r/\p{Cyrillic}/u}
          ],
          Regex.match?(pattern, text),
          do: label

    words ++ patterns
  end
end
