  # A file of the public tree, by its path there: in the public tree it is at
  # the top, beside this test's app; here, a page is the release's template.
  defp page(path) do
    top = Path.expand("../..", @plugin)

    [Path.join(top, path), Path.join([top, "priv/release", path])]
    |> Enum.find(&File.regular?/1)
  end

  defp page!(path) do
    found = page(path)
    assert found, "the public tree has no #{path}"
    # One line, so that a sentence held here may wrap anywhere in the page.
    found |> File.read!() |> String.replace(~r/\s+/, " ")
  end

  # What a file declares that the plugin must not have: an MCP server or a
  # hook, as a JSON key or a front-matter key, or a binary or a script.
  defp declares(path) do
    content = File.read!(path)

    json =
      if Path.extname(path) == ".json" do
        content
        |> JSON.decode!()
        |> keys()
        |> Enum.filter(&(&1 in ~w(mcpServers hooks lspServers)))
      else
        []
      end

    front =
      case front_matter(path) do
        {:ok, pairs} -> for {key, _} <- pairs, key in ~w(mcpServers mcp_servers hooks), do: key
        _ -> []
      end

    binary =
      cond do
        not String.valid?(content) -> ["not text"]
        String.starts_with?(content, "#!") -> ["a script"]
        true -> []
      end

    Enum.map(json, &"declares #{&1}") ++ Enum.map(front, &"front matter #{&1}") ++ binary
  end

  defp keys(map) when is_map(map),
    do: Enum.flat_map(map, fn {k, v} -> [k | keys(v)] end)

  defp keys(list) when is_list(list), do: Enum.flat_map(list, &keys/1)
  defp keys(_), do: []
  defp manifest, do: @manifest |> File.read!() |> JSON.decode!()

  # The front matter, as `[{key, raw value}]`, or an error saying why not.
  defp front_matter(path) do
    case File.read!(path) do
      "---\n" <> rest ->
        case String.split(rest, "\n---\n", parts: 2) do
          [block, _body] ->
            {:ok,
             for line <- String.split(block, "\n", trim: true) do
               case String.split(line, ": ", parts: 2) do
                 [key, value] -> {key, value}
                 _ -> {line, nil}
               end
             end}

          _ ->
            {:error, "the front matter is not closed"}
        end

      _ ->
        {:error, "the front matter does not open on line 1"}
    end
  end

  # A value every YAML parser reads the same way: a JSON string in double
  # quotes, or a plain scalar with no indicator first and no `: ` or ` #`.
  defp yaml_safe?(nil), do: false

  defp yaml_safe?("\"" <> _ = value) do
    match?({:ok, s} when is_binary(s), JSON.decode(value))
  end

  defp yaml_safe?(value) do
    value != "" and not String.contains?(value, [": ", " #"]) and
      not String.starts_with?(value, ~w(' [ { & * ! | > % @ ` - ? , #)) and
      String.trim(value) == value
  end

  defp scalar("\"" <> _ = value), do: JSON.decode!(value)
  defp scalar(value), do: value

