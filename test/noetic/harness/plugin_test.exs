defmodule Noetic.Harness.PluginTest do
  @moduledoc """
  The Claude Code plugin in `priv/plugin/`. `harness cut` carries it into the
  public tree as it is here.

  What is held here, and where each rule comes from:

  - **The manifest**, by the plugin directory's rules: a kebab-case `name` of
    at most 64 characters, a semver `version`, a `description` and an
    `author`, which `claude plugin validate --strict` fails without, and only
    fields Claude Code documents. `homepage` and `repository` name the public
    repository, which exists since an earlier change.
  - **What the directory's listing points to**: the
    documentation, support, privacy and terms URLs name files in the public
    repository, and each is held to a file the public tree has, so that no
    listing points at a page that is not there. The pages are the release's
    `docs/plugin-privacy.md`, `docs/plugin-terms.md` and
    `docs/plugin-support.md`, and the sentences a listing relies on are held
    here: the plugin collects and sends nothing, Apache-2.0 with no warranty,
    where to ask.
  - **The listing's classification**, by the portal's own lists as it printed
    them on 2026-10-01. It accepts five keys and drops any value outside its
    lists, so a value it would drop fails here instead. `life_area` is left
    out: its list was not given.
  - **What it must not carry:** no hooks, MCP or LSP servers, monitors,
    `bin/` or executables, in the manifest or in any file: a subagent's front
    matter can declare MCP servers and hooks too. `bin/` blocks installation
    on claude.ai and Cowork, and the directory's review holds a plugin that
    ships a binary or an MCP command. So the plugin is skills and subagents
    only, and the engine is installed separately.
  - **The files**, by the directory's pre-submission checklist as
    a published plugin of ours passed it: regular files only, fewer than 512, each
    under 256 KiB, names that work on Windows and macOS, and a README of at
    least 40 words.
  - **Front matter that any YAML parser reads the same way.**
    `claude plugin validate` checks a skill's front matter and not an
    agent's (tried 2026-09-30), and a plain value with `: ` in it,
    which every generated agent description has, is not YAML a strict parser
    accepts. Every value is either plain and free of YAML's indicators, or a
    double-quoted string that is also JSON.
  - **The subagents are the starter pack's nucleus**, generated by
    `Noetic.Harness.Plugin`. `Plugin.drift/1` compares them with what it
    builds now, so a change to the pack that does not reach the plugin fails
    here; `noetic-harness plugin` rewrites them.
  - **The four slash skills were commands** until an earlier change: Claude Code's
    documentation calls commands the older format, which skills supersede.
    Their front matter is the Agent Skills specification's, so `argument-hint`
    went into each description.
  - **What it does without the engine is said**, in the README and in every
    slash skill, and none runs anything but `noetic-harness`, `git status` and
    `echo`.
  - **Nothing names this repository, a machine or a person.** The same scan
    as `StarterPackTest`'s: its product names, its stack, a home directory, an e-mail
    address, a bead id or an ADR number. The publisher's name, the
    organisation's, is the one exception: the manifest's `author`, its links
    to the public repository, and the README's copyright line.
  - **The licence is the person's answer.** They answered
    on 2026-09-30: the upstream drop is
    theirs and ships under Apache-2.0, and the copyright holder is
    "NoeticEcho contributors". The manifest says Apache-2.0, the README
    says both, and `LICENSE` is the Apache License 2.0 text from apache.org,
    byte for byte: the same file as `priv/release/LICENSE`, which the cut
    writes at the top of the public tree.

  `claude plugin validate --strict` runs too, when a real Claude Code CLI is
  on the `PATH`. It makes no model call. CI has none, and the test says so
  rather than passing silently.
  """

